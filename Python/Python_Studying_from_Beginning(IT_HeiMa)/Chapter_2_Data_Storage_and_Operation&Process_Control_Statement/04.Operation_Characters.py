# Arithmetic operators
"""
+   加法        1 + 5 = 6
-   减法        8 - 3 = 5  
*   乘法        3 * 8 = 24
/   除法        8 / 2 = 4.0
//  整除        8 // 3 = 2
%   取余        8 % 3 = 2
**  幂指数      10 ** 3 = 1000
"""
print("10 + 4 = ", 10 + 4)
print("10 - 4 = ", 10 - 4)
print("10 * 4 = ", 10 * 4)
print("10 / 4 = ", 10 / 4)
print("10 // 4 = ", 10 // 4)
print("10 % 4 = ", 10 % 4)
print("10 ** 4 = ", 10 ** 4)

# Priority of arithmetic operators
print("0.1 + 10 / 4 ** 2 = ", 0.1 + 10 / 4 ** 2)

